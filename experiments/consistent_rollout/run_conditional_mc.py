def _safe_float(v: Any) -> float:
    try:
        x = float(v)
        return x if math.isfinite(x) else float("nan")
    except Exception:
        return float("nan")


def _clip01(p: np.ndarray) -> np.ndarray:
    return np.clip(np.asarray(p, dtype=np.float64), 1e-6, 1.0 - 1e-6)


def sample_alive_mask_gumbel_topk(
    alive_prob: np.ndarray,
    alive_count: int,
    rng: np.random.Generator,
) -> np.ndarray:
    """Sample exactly ``alive_count`` alive nodes using Gumbel-top-k logits."""
    p = _clip01(alive_prob).reshape(-1)
    n = int(p.shape[0])
    k = int(np.clip(round(float(alive_count)), 0, n))
    mask = np.zeros(n, dtype=bool)
    if k <= 0:
        return mask
    if k >= n:
        mask[:] = True
        return mask
    logits = np.log(p) - np.log1p(-p)
    scores = logits + rng.gumbel(size=n)
    idx = np.argpartition(scores, -k)[-k:]
    mask[idx] = True
    return mask


def conformal_correction(scores: Iterable[float], alpha: float = 0.10) -> float:
    """Finite-sample split-conformal correction using the higher empirical rank."""
    arr = np.asarray([x for x in scores if np.isfinite(x)], dtype=np.float64)
    if arr.size == 0:
        return 0.0
    arr.sort()
    rank = int(math.ceil((arr.size + 1) * (1.0 - float(alpha))))
    rank = min(max(rank, 1), arr.size)
    return float(arr[rank - 1])


def _bucket_key(start_idx: int, pred_idx: int) -> tuple[int, int]:
    return int(start_idx), int(pred_idx)


def _residual_stratum(r: MeanRolloutRecord, stratify_by: str) -> str:
    if stratify_by == "none":
        return "__all__"
    value = getattr(r, stratify_by)
    return str(value) if value is not None and pd.notna(value) else "__missing__"


def _residual_bucket_key(start_idx: int, pred_idx: int, stratum: str) -> tuple[int, int, str]:
    return int(start_idx), int(pred_idx), str(stratum)


def _experiment_checkpoint(runs_dir: Path, fold: int, checkpoint_name: str) -> Path:
    return runs_dir / f"fold{int(fold)}" / checkpoint_name


def _load_models_by_fold(runs_dir: Path, checkpoint_name: str) -> dict[int, tuple[Any, torch.Tensor, torch.Tensor, dict[str, Any]]]:
    models: dict[int, tuple[Any, torch.Tensor, torch.Tensor, dict[str, Any]]] = {}
    for fold in range(5):
        ckpt = _experiment_checkpoint(runs_dir, fold, checkpoint_name)
        if not ckpt.is_file():
            raise FileNotFoundError(f"Missing consistent rollout checkpoint: {ckpt}")
        model, mean, std = lib.load_model(ckpt)
        raw = torch.load(ckpt, map_location="cpu", weights_only=False)
        models[fold] = (model, mean, std, dict(raw.get("config", {})))
    return models


def _apply_delta_feat(src_xn: torch.Tensor, delta_feat: torch.Tensor) -> torch.Tensor:
    """Apply feature deltas, allowing core-only deltas on SSL-augmented graphs."""
    if delta_feat.shape[1] == src_xn.shape[1]:
        return src_xn + delta_feat
    if delta_feat.shape[1] > src_xn.shape[1]:
        raise ValueError(
            f"delta_feat width {delta_feat.shape[1]} exceeds state width {src_xn.shape[1]}"
        )
    out = src_xn.clone()
    out[:, : delta_feat.shape[1]] = out[:, : delta_feat.shape[1]] + delta_feat
    return out


def _burden_context_from_visit(
    xn: torch.Tensor,
    mean: torch.Tensor,
    std: torch.Tensor,
    *,
    volume_idx: int,
    alive: torch.Tensor | None = None,
) -> torch.Tensor:
    raw = xn * std + mean
    volume = raw[:, volume_idx].clamp_min(0.0)
    if alive is None:
        alive_weight = torch.ones_like(volume)
    else:
        alive_weight = alive.to(device=xn.device, dtype=xn.dtype).reshape(-1)
    ftv = (volume * alive_weight).sum()
    alive_count = alive_weight.sum()
    node_count = torch.as_tensor(float(xn.shape[0]), device=xn.device, dtype=xn.dtype)
    mean_active_volume = ftv / alive_count.clamp_min(1.0)
    alive_fraction = alive_count / node_count.clamp_min(1.0)
    return torch.stack(
        [
            torch.log1p(ftv),
            torch.log1p(alive_count),
            torch.log1p(node_count),
            torch.log1p(mean_active_volume),
            alive_fraction.clamp(0.0, 1.0),
        ]
    )


def _predict_ftv_from_outputs(
    out: dict[str, torch.Tensor],
    pred_xn: torch.Tensor,
    alive_prob: torch.Tensor,
    mean: torch.Tensor,
    std: torch.Tensor,
    *,
    volume_idx: int,
    graph_ftv_residual_cap_ml: float,
) -> tuple[torch.Tensor, torch.Tensor, str]:
    pred_raw = pred_xn * std + mean
    node_ftv = (pred_raw[:, volume_idx].clamp_min(0.0) * alive_prob.reshape(-1)).sum()
    pred_ftv = node_ftv
    source = "node_sum"
    if "graph_ftv_affine" in out:
        affine = out["graph_ftv_affine"].reshape(-1)
        scale = torch.nn.functional.softplus(affine[0]).clamp(0.25, 4.0)
        pred_ftv = (scale * node_ftv + affine[1]).clamp_min(0.0)
        source = "graph_readout"
    if "graph_ftv_residual" in out and graph_ftv_residual_cap_ml > 0.0:
        cap = torch.as_tensor(
            float(graph_ftv_residual_cap_ml),
            device=pred_ftv.device,
            dtype=pred_ftv.dtype,
        )
        resid = cap * torch.tanh(out["graph_ftv_residual"].reshape(()))
        pred_ftv = (pred_ftv + resid).clamp_min(0.0)
        source = "graph_readout"
    if "graph_ftv_log" in out:
        pred_ftv = torch.expm1(out["graph_ftv_log"].reshape(())).clamp_min(0.0)
        source = "graph_readout"
    return pred_ftv, node_ftv, source


@torch.no_grad()
def rollout_from_visit_device(
    model: Any,
    mean: torch.Tensor,
    std: torch.Tensor,
    g: dict,
    *,
    start_visit: int,
    device: torch.device,
    k_spatial: int = 8,
    edge_mode: str = "full",
    edge_attr_mode: str = "none",
    volume_idx: int = 1,
) -> list[dict[str, Any]]:
    """Device-aware version of ``consistent_twin_lib.rollout_from_visit``."""
    if start_visit < 0 or start_visit >= len(VISITS) - 1:
        raise ValueError(f"start_visit must be in [0, {len(VISITS) - 2}]")

    model = model.to(device)
    mean_d = mean.to(device)
    std_d = std.to(device)
    x = (g["x"].float().to(device) - mean_d) / std_d
    pos = g["pos"].float().to(device)
    off = [int(v) for v in g["visit_offsets"].tolist()]
    n_visits = len(off) - 1

    history_x: list[torch.Tensor] = []
    history_pos: list[torch.Tensor] = []
    history_t: list[torch.Tensor] = []
    for v in range(start_visit + 1):
        sl = slice(off[v], off[v + 1])
        xv = x[sl].clone()
        pv = pos[sl].clone()
        tv = torch.full((xv.shape[0],), float(v), dtype=x.dtype, device=device)
        history_x.append(xv)
        history_pos.append(pv)
        history_t.append(tv)
    burden_context = None
    if getattr(model, "burden_context_dim", 0):
        start_sl = slice(off[start_visit], off[start_visit + 1])
        alive_start = g["alive"][start_sl].float().to(device)
        burden_context = _burden_context_from_visit(
            history_x[-1],
            mean_d,
            std_d,
            volume_idx=int(volume_idx),
            alive=alive_start,
        )

    rows: list[dict[str, Any]] = []
    for pred_v in range(start_visit + 1, n_visits):
        x_cat = torch.cat(history_x, dim=0)
        pos_cat = torch.cat(history_pos, dim=0)
        t_cat = torch.cat(history_t, dim=0)
        edge_index, edge_attr, edge_type = build_history_graph_with_types(
            history_pos,
            history_x,
            k_spatial=k_spatial,
            edge_mode=edge_mode,
            edge_attr_mode=edge_attr_mode,
        )
        out = model(
            x_cat,
            pos_cat,
            t_cat,
            edge_index,
            edge_attr=edge_attr,
            edge_type=edge_type if getattr(model, "conv_type", "lsgc") == "relational" else None,
            burden_context=burden_context,
        )

        n_last = int(history_x[-1].shape[0])
        sl_last = slice(x_cat.shape[0] - n_last, x_cat.shape[0])
        dpos = out["delta_pos"][sl_last]
        dfeat = out["delta_feat"][sl_last]
        alive_prob = torch.sigmoid(out["alive_logit"][sl_last])

        x_next = _apply_delta_feat(history_x[-1], dfeat)
        pos_next = history_pos[-1] + dpos
        graph_ftv_pred, node_ftv_pred, graph_ftv_source = _predict_ftv_from_outputs(
            out,
            x_next,
            alive_prob,
            mean_d,
            std_d,
            volume_idx=int(volume_idx),
            graph_ftv_residual_cap_ml=float(getattr(model, "_graph_ftv_residual_cap_ml", 1.0)),
        )

        obs_sl = slice(off[pred_v], off[pred_v + 1])
        x_obs = g["x"][obs_sl].float().cpu().numpy()
        pos_obs = g["pos"][obs_sl].float().cpu().numpy()
        alive_obs = g["alive"][obs_sl].detach().cpu().numpy().astype(bool)

        rows.append(
            {
                "visit_idx": pred_v,
                "visit_name": VISITS[pred_v],
                "pos_pred": pos_next.detach().cpu().numpy(),
                "x_pred": (x_next * std_d + mean_d).detach().cpu().numpy(),
                "alive_prob": alive_prob.detach().cpu().numpy(),
                "graph_ftv_pred_ml": float(graph_ftv_pred.detach().cpu().item()),
                "graph_ftv_node_sum_ml": float(node_ftv_pred.detach().cpu().item()),
                "graph_ftv_source": graph_ftv_source,
                "pos_obs": pos_obs,
                "x_obs": x_obs,
                "alive_obs": alive_obs,
            }
        )

        history_x.append(x_next)
        history_pos.append(pos_next)
        history_t.append(torch.full((x_next.shape[0],), float(pred_v), dtype=x.dtype, device=device))
    return rows


def _cohort_metadata(cohort: pd.DataFrame) -> dict[str, dict[str, Any]]:
    rows: dict[str, dict[str, Any]] = {}
    for _, r in cohort.iterrows():
        pid = str(r["patient_id"])
        rows[pid] = {
            "collection": str(r["collection"]) if pd.notna(r.get("collection", None)) else None,
            "pCR": int(r["pCR"]) if pd.notna(r.get("pCR", None)) else None,
            "subtype": str(r["subtype"]) if pd.notna(r.get("subtype", None)) else None,
        }
    return rows


def _select_patient_folds(
    folds: pd.DataFrame,
    graphs_root: Path,
    patient_list: Path | None,
    patient_limit: int,
) -> list[tuple[str, int]]:
    fold_map = {str(r.patient_id): int(r.fold) for r in folds.itertuples(index=False)}
    if patient_list is not None and patient_list.is_file():
        pids = [ln.strip() for ln in patient_list.read_text().splitlines() if ln.strip()]
    else:
        pids = folds["patient_id"].astype(str).tolist()
    out = [
        (pid, fold_map[pid])
        for pid in pids
        if pid in fold_map and _graph_path(pid, graphs_root, fold_map[pid]).is_file()
    ]
    if patient_limit > 0:
        out = out[: int(patient_limit)]
    return out


def _select_eval_records(
    records: list[MeanRolloutRecord],
    eval_patient_list: Path | None,
    eval_shard_index: int | None,
    eval_num_shards: int | None,
) -> list[MeanRolloutRecord]:
    """Select rollout records to score while retaining full-cohort residual pools."""
    selected = list(records)
    if eval_patient_list is not None:
        if not eval_patient_list.is_file():
            raise FileNotFoundError(f"Missing eval patient list: {eval_patient_list}")
        keep = {ln.strip() for ln in eval_patient_list.read_text().splitlines() if ln.strip()}
        selected = [r for r in selected if r.patient_id in keep]

    if eval_shard_index is not None or eval_num_shards is not None:
        if eval_shard_index is None or eval_num_shards is None:
            raise ValueError("--eval-shard-index and --eval-num-shards must be provided together")
        n = int(eval_num_shards)
        idx = int(eval_shard_index)
        if n <= 0:
            raise ValueError("--eval-num-shards must be positive")
        if idx < 0 or idx >= n:
            raise ValueError("--eval-shard-index must be in [0, eval_num_shards)")
        patient_ids = sorted({r.patient_id for r in selected})
        shard_patients = {pid for j, pid in enumerate(patient_ids) if j % n == idx}
        selected = [r for r in selected if r.patient_id in shard_patients]

    return selected


def _select_calibration_records(
    records: list[MeanRolloutRecord],
    calibration_patient_list: Path | None,
) -> list[MeanRolloutRecord]:
    if calibration_patient_list is None:
        return list(records)
    if not calibration_patient_list.is_file():
        raise FileNotFoundError(f"Missing calibration patient list: {calibration_patient_list}")
    keep = {ln.strip() for ln in calibration_patient_list.read_text().splitlines() if ln.strip()}
    return [r for r in records if r.patient_id in keep]


def _observed_ftv_t0(g: dict, volume_idx: int) -> float:
    off = g["visit_offsets"].tolist()
    sl = slice(int(off[0]), int(off[1]))
    return _safe_float(g["x"][sl, volume_idx].detach().cpu().numpy().sum())


def _graph_path(pid: str, graphs_root: Path, fold: int) -> Path:
    fold_path = graphs_root / f"fold{int(fold)}" / f"{pid}.pt"
    if fold_path.is_file():
        return fold_path
    return graphs_root / f"{pid}.pt"


def _load_consistent_graph(pid: str, graphs_root: Path, fold: int) -> dict:
    path = _graph_path(pid, graphs_root, fold)
    if not path.is_file():
        raise FileNotFoundError(path)
    return torch.load(path, map_location="cpu", weights_only=False)


def build_mean_rollout_records(
    *,
    patient_folds: list[tuple[str, int]],
    models_by_fold: dict[int, tuple[Any, torch.Tensor, torch.Tensor, dict[str, Any]]],
    graphs_root: Path,
    cohort_meta: dict[str, dict[str, Any]],
    start_visits: tuple[int, ...],
    volume_idx: int,
    device: torch.device,
) -> list[MeanRolloutRecord]:
    records: list[MeanRolloutRecord] = []
    for i, (pid, fold) in enumerate(patient_folds, 1):
        model, mean, std, cfg = models_by_fold[int(fold)]
        k_spatial = int(cfg.get("k_spatial", 8))
        edge_mode = str(cfg.get("edge_mode", "full"))
        edge_attr_mode = str(cfg.get("edge_attr_mode", "none"))
        g = _load_consistent_graph(pid, graphs_root, int(fold))
        ftv_t0 = _observed_ftv_t0(g, volume_idx)
        meta = cohort_meta.get(pid, {})
        for start_idx in start_visits:
            try:
                steps = rollout_from_visit_device(
                    model,
                    mean,
                    std,
                    g,
                    start_visit=int(start_idx),
                    device=device,
                    k_spatial=k_spatial,
                    edge_mode=edge_mode,
                    edge_attr_mode=edge_attr_mode,
                    volume_idx=int(volume_idx),
                )
            except Exception as exc:
                print(f"[warn] {pid} fold={fold} start={start_idx}: rollout failed: {exc}", flush=True)
                continue
            for step_i, step in enumerate(steps, 1):
                alive_prob = np.asarray(step["alive_prob"], dtype=np.float64).reshape(-1)
                x_pred = np.asarray(step["x_pred"], dtype=np.float64)
                x_obs = np.asarray(step["x_obs"], dtype=np.float64)
                pred_vol = np.clip(x_pred[:, volume_idx], 0.0, None)
                obs_vol = np.clip(x_obs[:, volume_idx], 0.0, None)
                pred_ftv_node = _safe_float(np.sum(pred_vol * alive_prob))
                pred_ftv = _safe_float(step.get("graph_ftv_pred_ml", pred_ftv_node))
                pred_ftv_source = str(step.get("graph_ftv_source", "node_sum"))
                if not np.isfinite(pred_ftv):
                    pred_ftv = pred_ftv_node
                    pred_ftv_source = "node_sum"
                obs_ftv = _safe_float(np.sum(obs_vol))
                records.append(
                    MeanRolloutRecord(
                        patient_id=pid,
                        fold=int(fold),
                        start_idx=int(start_idx),
                        pred_idx=int(step["visit_idx"]),
                        start_visit=VISITS[int(start_idx)],
                        predicted_visit=str(step["visit_name"]),
                        rollout_depth=step_i,
                        n_sv=int(alive_prob.shape[0]),
                        pred_pos=np.asarray(step["pos_pred"], dtype=np.float64),
                        obs_pos=np.asarray(step["pos_obs"], dtype=np.float64),
                        x_pred=x_pred,
                        x_obs=x_obs,
                        alive_prob=alive_prob,
                        alive_obs=np.asarray(step["alive_obs"], dtype=bool).reshape(-1),
                        pred_ftv_ml=pred_ftv,
                        obs_ftv_ml=obs_ftv,
                        ftv_t0_ml=ftv_t0,
                        pred_ftv_source=pred_ftv_source,
                        collection=meta.get("collection"),
                        pCR=meta.get("pCR"),
                        subtype=meta.get("subtype"),
                    )
                )
        if i % 50 == 0 or i == len(patient_folds):
            print(f"[mean] {i}/{len(patient_folds)} patients -> {len(records)} rollout records", flush=True)
    return records


def residual_from_record(r: MeanRolloutRecord, volume_idx: int) -> ResidualRecord:
    alive_obs = np.asarray(r.alive_obs, dtype=bool)
    pred_pos = np.asarray(r.pred_pos, dtype=np.float64)
    obs_pos = np.asarray(r.obs_pos, dtype=np.float64)
    valid = alive_obs & np.isfinite(pred_pos).all(axis=1) & np.isfinite(obs_pos).all(axis=1)
    if valid.any():
        disp = obs_pos[valid] - pred_pos[valid]
        global_disp = disp.mean(axis=0)
        local_disp = disp - global_disp[None, :]
    else:
        global_disp = np.zeros(3, dtype=np.float64)
        local_disp = np.empty((0, 3), dtype=np.float64)

    pred_vol = np.clip(r.x_pred[:, volume_idx], 0.0, None)
    obs_vol = np.clip(r.x_obs[:, volume_idx], 0.0, None)
    vvalid = valid & np.isfinite(pred_vol) & np.isfinite(obs_vol)
    log_volume_resids = np.log1p(obs_vol[vvalid]) - np.log1p(pred_vol[vvalid])
    return ResidualRecord(
        patient_id=r.patient_id,
        fold=r.fold,
        start_idx=r.start_idx,
        pred_idx=r.pred_idx,
        n_sv=r.n_sv,
        pred_ftv_ml=r.pred_ftv_ml,
        obs_ftv_ml=r.obs_ftv_ml,
        ftv_t0_ml=r.ftv_t0_ml,
        alive_mass_det=float(np.asarray(r.alive_prob, dtype=np.float64).sum()),
        collection=r.collection,
        pCR=r.pCR,
        subtype=r.subtype,
        ftv_resid=_safe_float(r.obs_ftv_ml - r.pred_ftv_ml),
        alive_count_resid=_safe_float(float(alive_obs.sum()) - float(np.asarray(r.alive_prob).sum())),
        global_disp_resid=global_disp,
        local_disp_resids=local_disp,
        log_volume_resids=np.asarray(log_volume_resids, dtype=np.float64),
    )


def build_residual_buckets(
    records: list[MeanRolloutRecord],
    volume_idx: int,
    stratify_by: str = "none",
) -> dict[tuple[int, int, str], list[ResidualRecord]]:
    buckets: dict[tuple[int, int, str], list[ResidualRecord]] = {}
    for r in records:
        stratum = _residual_stratum(r, stratify_by)
        buckets.setdefault(_residual_bucket_key(r.start_idx, r.pred_idx, stratum), []).append(
            residual_from_record(r, volume_idx)
        )
    return buckets


def _residual_metric(resid: ResidualRecord, metric: str) -> float:
    if metric == "predicted_ftv":
        return _safe_float(resid.pred_ftv_ml)
    if metric == "baseline_ftv":
        return _safe_float(resid.ftv_t0_ml)
    if metric == "alive_mass":
        return _safe_float(resid.alive_mass_det)
    raise ValueError(f"Unknown residual metric: {metric}")


def _target_metric(target: MeanRolloutRecord, metric: str) -> float:
    if metric == "predicted_ftv":
        return _safe_float(target.pred_ftv_ml)
    if metric == "baseline_ftv":
        return _safe_float(target.ftv_t0_ml)
    if metric == "alive_mass":
        return _safe_float(float(np.asarray(target.alive_prob, dtype=np.float64).sum()))
    raise ValueError(f"Unknown target metric: {metric}")


def _quantile_filtered_candidates(
    candidates: list[ResidualRecord],
    target: MeanRolloutRecord,
    metric: str,
    *,
    min_patients: int,
    quantile_bins: int,
) -> tuple[list[ResidualRecord], str]:
    if not candidates:
        return candidates, f"{metric}:empty"
    bins = max(2, int(quantile_bins))
    target_value = _target_metric(target, metric)
    vals = np.asarray([_residual_metric(r, metric) for r in candidates], dtype=np.float64)
    finite = np.isfinite(vals)
    if not np.isfinite(target_value) or finite.sum() < max(int(min_patients), bins):
        return candidates, f"{metric}:fallback_all"
    qs = np.linspace(0.0, 1.0, bins + 1)
    edges = np.quantile(vals[finite], qs)
    edges[0] = -np.inf
    edges[-1] = np.inf
    idx = int(np.searchsorted(edges, target_value, side="right") - 1)
    idx = int(np.clip(idx, 0, bins - 1))
    lo = float(edges[idx])
    hi = float(edges[idx + 1])
    chosen = [
        r
        for r, v in zip(candidates, vals, strict=False)
        if np.isfinite(v) and lo <= float(v) <= hi
    ]
    if len(chosen) >= int(min_patients):
        return chosen, f"{metric}:qbin{idx + 1}/{bins}:n={len(chosen)}"
    return candidates, f"{metric}:fallback_all:n={len(chosen)}<min{int(min_patients)}"


def _select_residual_candidates(
    candidates: list[ResidualRecord],
    target: MeanRolloutRecord,
    sampler: SamplerConfig,
) -> tuple[list[ResidualRecord], str]:
    mode = str(sampler.mode)
    if mode == "bucket_baseline":
        return candidates, "bucket_baseline"
    if mode == "predicted_ftv_stratified":
        return _quantile_filtered_candidates(
            candidates,
            target,
            "predicted_ftv",
            min_patients=sampler.min_patients,
            quantile_bins=sampler.quantile_bins,
        )
    if mode == "baseline_ftv_stratified":
        return _quantile_filtered_candidates(
            candidates,
            target,
            "baseline_ftv",
            min_patients=sampler.min_patients,
            quantile_bins=sampler.quantile_bins,
        )
    if mode == "alive_mass_stratified":
        return _quantile_filtered_candidates(
            candidates,
            target,
            "alive_mass",
            min_patients=sampler.min_patients,
            quantile_bins=sampler.quantile_bins,
        )
    if mode == "hybrid_backoff":
        for metric in ("predicted_ftv", "baseline_ftv", "alive_mass"):
            chosen, rule = _quantile_filtered_candidates(
                candidates,
                target,
                metric,
                min_patients=sampler.min_patients,
                quantile_bins=sampler.quantile_bins,
            )
            if len(chosen) < len(candidates):
                return chosen, f"hybrid:{rule}"
        if target.subtype is not None and pd.notna(target.subtype):
            chosen = [r for r in candidates if r.subtype == target.subtype]
            if len(chosen) >= int(sampler.min_patients):
                return chosen, f"hybrid:subtype={target.subtype}:n={len(chosen)}"
        return candidates, "hybrid:fallback_all"
    raise ValueError(f"Unknown residual sampler mode: {mode}")


def _pooled_node_residuals(patient_resids: list[ResidualRecord]) -> tuple[np.ndarray, np.ndarray]:
    local = [r.local_disp_resids for r in patient_resids if r.local_disp_resids.size]
    logv = [r.log_volume_resids.reshape(-1) for r in patient_resids if r.log_volume_resids.size]
    local_arr = np.concatenate(local, axis=0) if local else np.empty((0, 3), dtype=np.float64)
    logv_arr = np.concatenate(logv, axis=0) if logv else np.empty((0,), dtype=np.float64)
    return local_arr, logv_arr


def candidate_residuals(
    bucket: list[ResidualRecord],
    target: MeanRolloutRecord | str,
    sampler: SamplerConfig | None = None,
) -> CandidateResidualSet | tuple[list[ResidualRecord], np.ndarray, np.ndarray]:
    """Return residual candidates excluding the target patient.

    The string target path is kept for the lightweight unit test and for
    backward-compatible helper use.  Production calls pass a MeanRolloutRecord
    so the sampler can use prediction-time patient context.
    """
    if isinstance(target, str):
        patient_resids = [r for r in bucket if r.patient_id != target]
        local_arr, logv_arr = _pooled_node_residuals(patient_resids)
        return patient_resids, local_arr, logv_arr

    cfg = sampler or SamplerConfig()
    bucket_candidates = [r for r in bucket if r.patient_id != target.patient_id]
    patient_resids, selection_rule = _select_residual_candidates(bucket_candidates, target, cfg)
    local_arr, logv_arr = _pooled_node_residuals(patient_resids)
    return CandidateResidualSet(
        patient_resids=patient_resids,
        local_resids=local_arr,
        log_volume_resids=logv_arr,
        selection_rule=selection_rule,
        n_bucket_candidates=len(bucket_candidates),
    )


def _empty_sample_metrics() -> dict[str, float]:
    return {m: float("nan") for m in PRIMARY_METRICS}


def _primary_cloud_metrics(
    pred_pos: np.ndarray,
    obs_pos: np.ndarray,
    pred_ftv: float,
    obs_ftv: float,
    pred_alive_count: int,
    obs_alive_count: int,
) -> dict[str, float]:
    if pred_pos.shape[0] == 0 or obs_pos.shape[0] == 0:
        dice = 1.0 if pred_pos.shape[0] == 0 and obs_pos.shape[0] == 0 else 0.0
        return {
            "swd_mm": float("nan"),
            "chamfer_mm": float("nan"),
            "dice": float(dice),
            "ftv_abs_err_ml": abs(float(pred_ftv) - float(obs_ftv)),
            "alive_count_abs_err": abs(int(pred_alive_count) - int(obs_alive_count)),
        }
    dice, _ = voxelized_dice_iou(pred_pos, obs_pos)
    return {
        "swd_mm": _safe_float(sliced_wasserstein(pred_pos, obs_pos)),
        "chamfer_mm": _safe_float(chamfer_position(pred_pos, obs_pos)),
        "dice": _safe_float(dice),
        "ftv_abs_err_ml": abs(float(pred_ftv) - float(obs_ftv)),
        "alive_count_abs_err": abs(int(pred_alive_count) - int(obs_alive_count)),
    }


def simulate_record(
    r: MeanRolloutRecord,
    bucket: list[ResidualRecord],
    *,
    n_mc: int,
    rng: np.random.Generator,
    eps_pcr: float,
    volume_idx: int,
    sampler: SamplerConfig | None = None,
    residual_stratify_by: str = "none",
    residual_stratum: str = "__all__",
    metric_draws: int = 0,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    candidate_set = candidate_residuals(bucket, r, sampler or SamplerConfig())
    assert isinstance(candidate_set, CandidateResidualSet)
    patient_resids = candidate_set.patient_resids
    local_resids = candidate_set.local_resids
    logvol_resids = candidate_set.log_volume_resids
    n_candidates = len(patient_resids)
    obs_alive_count = int(np.asarray(r.alive_obs, dtype=bool).sum())
    obs_cloud = np.asarray(r.obs_pos, dtype=np.float64)[np.asarray(r.alive_obs, dtype=bool)]
    pred_vol = np.clip(np.asarray(r.x_pred[:, volume_idx], dtype=np.float64), 0.0, None)
    alive_mass = float(np.asarray(r.alive_prob, dtype=np.float64).sum())
    sample_rows: list[dict[str, Any]] = []
    ftv_samples: list[float] = []

    if n_candidates:
        chosen = rng.integers(0, n_candidates, size=int(n_mc))
    else:
        chosen = np.zeros(int(n_mc), dtype=np.int64)

    for draw in range(int(n_mc)):
        if n_candidates:
            res = patient_resids[int(chosen[draw])]
            ftv_resid = float(res.ftv_resid)
            alive_resid = float(res.alive_count_resid)
            global_resid = np.asarray(res.global_disp_resid, dtype=np.float64)
        else:
            ftv_resid = 0.0
            alive_resid = 0.0
            global_resid = np.zeros(3, dtype=np.float64)

        alive_count = int(np.clip(round(alive_mass + alive_resid), 0, r.n_sv))
        alive_mask = sample_alive_mask_gumbel_topk(r.alive_prob, alive_count, rng)

        if local_resids.shape[0]:
            local_idx = rng.integers(0, local_resids.shape[0], size=r.n_sv)
            local_noise = local_resids[local_idx]
        else:
            local_noise = np.zeros_like(r.pred_pos, dtype=np.float64)
        pos_sample = np.asarray(r.pred_pos, dtype=np.float64) + global_resid[None, :] + local_noise

        if logvol_resids.shape[0]:
            lv_idx = rng.integers(0, logvol_resids.shape[0], size=r.n_sv)
            lv_noise = logvol_resids[lv_idx]
        else:
            lv_noise = np.zeros(r.n_sv, dtype=np.float64)
        vol_sample = np.expm1(np.log1p(pred_vol) + lv_noise)
        vol_sample = np.clip(vol_sample, 0.0, None)
        ftv_node = float(vol_sample[alive_mask].sum())
        if r.pred_ftv_source == "graph_readout":
            ftv_sample = max(0.0, float(r.pred_ftv_ml) + ftv_resid)
        else:
            ftv_sample = max(0.0, ftv_node + ftv_resid)
        ftv_samples.append(ftv_sample)

        if metric_draws <= 0 or draw < metric_draws:
            metrics = _primary_cloud_metrics(
                pos_sample[alive_mask],
                obs_cloud,
                pred_ftv=ftv_sample,
                obs_ftv=r.obs_ftv_ml,
                pred_alive_count=int(alive_mask.sum()),
                obs_alive_count=obs_alive_count,
            )
        else:
            metrics = _empty_sample_metrics()

        sample_rows.append(
            {
                "patient_id": r.patient_id,
                "fold": r.fold,
                "start_visit": r.start_visit,
                "predicted_visit": r.predicted_visit,
                "start_idx": r.start_idx,
                "pred_idx": r.pred_idx,
                "residual_stratify_by": residual_stratify_by,
                "residual_stratum": residual_stratum,
                "residual_sampler_mode": (sampler or SamplerConfig()).mode,
                "sampler_selection_rule": candidate_set.selection_rule,
                "rollout_depth": r.rollout_depth,
                "draw": draw,
                "n_bucket_calibration_patients": candidate_set.n_bucket_candidates,
                "n_calibration_patients": n_candidates,
                "ftv_sample_ml": ftv_sample,
                "alive_count_sample": int(alive_mask.sum()),
                **metrics,
            }
        )

    arr = np.asarray(ftv_samples, dtype=np.float64)
    raw_lo, raw_hi = np.percentile(arr, [5, 95]) if arr.size else (float("nan"), float("nan"))
    metric_cols = {
        f"{m}_mc_mean": _safe_float(np.nanmean([row[m] for row in sample_rows]))
        for m in PRIMARY_METRICS
    }
    summary = {
        "patient_id": r.patient_id,
        "fold": r.fold,
        "collection": r.collection,
        "pCR": r.pCR,
        "subtype": r.subtype,
        "start_visit": r.start_visit,
        "predicted_visit": r.predicted_visit,
        "start_idx": r.start_idx,
        "pred_idx": r.pred_idx,
        "residual_stratify_by": residual_stratify_by,
        "residual_stratum": residual_stratum,
        "residual_sampler_mode": (sampler or SamplerConfig()).mode,
        "sampler_selection_rule": candidate_set.selection_rule,
        "rollout_depth": r.rollout_depth,
        "n_mc": int(arr.size),
        "n_supervoxels": r.n_sv,
        "n_bucket_calibration_patients": candidate_set.n_bucket_candidates,
        "n_calibration_patients": n_candidates,
        "pred_ftv_det_ml": r.pred_ftv_ml,
        "pred_ftv_source": r.pred_ftv_source,
        "obs_ftv_ml": r.obs_ftv_ml,
        "ftv_mc_mean_ml": _safe_float(np.mean(arr)),
        "ftv_mc_std_ml": _safe_float(np.std(arr)),
        "ftv_mc_median_ml": _safe_float(np.median(arr)),
        "ftv_raw_p05_ml": _safe_float(raw_lo),
        "ftv_raw_p95_ml": _safe_float(raw_hi),
        "ftv_raw_width90_ml": _safe_float(raw_hi - raw_lo),
        "coverage90_ftv_raw": int(raw_lo <= r.obs_ftv_ml <= raw_hi) if np.isfinite(raw_lo) else 0,
        "crps_ftv": _safe_float(crps_empirical(arr, r.obs_ftv_ml)),
        "pcr_prob_mc": _safe_float(np.mean(arr < float(eps_pcr))),
        "alive_count_obs": obs_alive_count,
        "alive_mass_det": alive_mass,
        "ftv_t0_ml": r.ftv_t0_ml,
        **metric_cols,
    }
    return sample_rows, summary


def _raw_ftv_nonconformity(row: dict[str, Any]) -> float:
    score = max(
        float(row["ftv_raw_p05_ml"]) - float(row["obs_ftv_ml"]),
        float(row["obs_ftv_ml"]) - float(row["ftv_raw_p95_ml"]),
        0.0,
    )
    return _safe_float(score)


def add_conformal_intervals(
    summaries: list[dict[str, Any]],
    alpha: float,
    calibration_summaries: list[dict[str, Any]] | None = None,
) -> list[dict[str, Any]]:
    calibration_rows = summaries if calibration_summaries is None else calibration_summaries
    by_bucket: dict[tuple[int, int, str], list[dict[str, Any]]] = {}
    for row in calibration_rows:
        row["ftv_raw_nonconformity_ml"] = _raw_ftv_nonconformity(row)
        stratum = str(row.get("residual_stratum", "__all__"))
        by_bucket.setdefault(_residual_bucket_key(row["start_idx"], row["pred_idx"], stratum), []).append(row)

    for row in summaries:
        row["ftv_raw_nonconformity_ml"] = _raw_ftv_nonconformity(row)
        stratum = str(row.get("residual_stratum", "__all__"))
        peers = [
            x["ftv_raw_nonconformity_ml"]
            for x in by_bucket.get(_residual_bucket_key(row["start_idx"], row["pred_idx"], stratum), [])
            if x["patient_id"] != row["patient_id"]
        ]
        q = conformal_correction(peers, alpha=alpha)
        lo = float(row["ftv_raw_p05_ml"]) - q
        hi = float(row["ftv_raw_p95_ml"]) + q
        row["ftv_conformal_q_ml"] = q
        row["ftv_conformal_p05_ml"] = lo
        row["ftv_conformal_p95_ml"] = hi
        row["ftv_conformal_width90_ml"] = hi - lo
        row["coverage90_ftv_conformal"] = int(lo <= float(row["obs_ftv_ml"]) <= hi)
    return summaries


def aggregate_summary(per_patient: pd.DataFrame) -> dict[str, Any]:
    group_cols = ["start_visit", "predicted_visit"]
    metric_cols = [
        "ftv_mc_mean_ml",
        "ftv_mc_std_ml",
        "ftv_raw_width90_ml",
        "ftv_conformal_width90_ml",
        "coverage90_ftv_raw",
        "coverage90_ftv_conformal",
        "crps_ftv",
        "pcr_prob_mc",
        *[f"{m}_mc_mean" for m in PRIMARY_METRICS],
    ]
    rows: list[dict[str, Any]] = []
    for keys, grp in per_patient.groupby(group_cols, dropna=False):
        start_visit, predicted_visit = keys
        out: dict[str, Any] = {
            "start_visit": start_visit,
            "predicted_visit": predicted_visit,
            "n_patients": int(grp["patient_id"].nunique()),
            "mean_rollout_depth": _safe_float(pd.to_numeric(grp["rollout_depth"], errors="coerce").mean()),
        }
        for col in metric_cols:
            vals = pd.to_numeric(grp[col], errors="coerce").dropna().to_numpy(dtype=np.float64)
            out[f"{col}_mean"] = _safe_float(np.mean(vals)) if vals.size else float("nan")
            out[f"{col}_se"] = _safe_float(np.std(vals, ddof=1) / math.sqrt(vals.size)) if vals.size > 1 else float("nan")
        rows.append(out)

    t3 = [
        r for r in rows
        if r["predicted_visit"] == "T3"
    ]
    t3 = sorted(t3, key=lambda x: VISITS.index(str(x["start_visit"])))
    shrink = []
    for r in t3:
        shrink.append(
            {
                "conditioning": f"{','.join(VISITS[:VISITS.index(str(r['start_visit'])) + 1])}->T3",
                "start_visit": r["start_visit"],
                "n_patients": r["n_patients"],
                "ftv_conformal_width90_ml_mean": r.get("ftv_conformal_width90_ml_mean"),
                "ftv_raw_width90_ml_mean": r.get("ftv_raw_width90_ml_mean"),
                "crps_ftv_mean": r.get("crps_ftv_mean"),
                "ftv_abs_err_ml_mc_mean_mean": r.get("ftv_abs_err_ml_mc_mean_mean"),
            }
        )

    return {
        "n_rows": int(len(per_patient)),
        "n_patients": int(per_patient["patient_id"].nunique() if len(per_patient) else 0),
        "by_conditioning_visit": rows,
        "t3_uncertainty_shrinkage": shrink,
    }


def calibration_summary(
    residual_buckets: dict[tuple[int, int, str], list[ResidualRecord]],
    per_patient: pd.DataFrame,
) -> dict[str, Any]:
    rows: list[dict[str, Any]] = []
    for (start_idx, pred_idx, stratum), bucket in sorted(residual_buckets.items()):
        local_n = int(sum(r.local_disp_resids.shape[0] for r in bucket))
        logv_n = int(sum(r.log_volume_resids.shape[0] for r in bucket))
        ftv_resids = np.asarray([r.ftv_resid for r in bucket], dtype=np.float64)
        alive_resids = np.asarray([r.alive_count_resid for r in bucket], dtype=np.float64)
        grp = per_patient[
            (per_patient["start_idx"] == start_idx)
            & (per_patient["pred_idx"] == pred_idx)
            & (per_patient["residual_stratum"] == stratum)
        ]
        rows.append(
            {
                "start_visit": VISITS[start_idx],
                "predicted_visit": VISITS[pred_idx],
                "residual_stratum": stratum,
                "n_records": int(len(bucket)),
                "n_unique_patients": int(len({r.patient_id for r in bucket})),
                "n_local_disp_residuals": local_n,
                "n_log_volume_residuals": logv_n,
                "ftv_resid_mean_ml": _safe_float(np.nanmean(ftv_resids)) if ftv_resids.size else float("nan"),
                "ftv_resid_std_ml": _safe_float(np.nanstd(ftv_resids)) if ftv_resids.size else float("nan"),
                "alive_count_resid_mean": _safe_float(np.nanmean(alive_resids)) if alive_resids.size else float("nan"),
                "alive_count_resid_std": _safe_float(np.nanstd(alive_resids)) if alive_resids.size else float("nan"),
                "raw_coverage90_ftv": _safe_float(pd.to_numeric(grp["coverage90_ftv_raw"], errors="coerce").mean()) if len(grp) else float("nan"),
                "conformal_coverage90_ftv": _safe_float(pd.to_numeric(grp["coverage90_ftv_conformal"], errors="coerce").mean()) if len(grp) else float("nan"),
                "mean_conformal_q_ml": _safe_float(pd.to_numeric(grp["ftv_conformal_q_ml"], errors="coerce").mean()) if len(grp) else float("nan"),
                "mean_crps_ftv": _safe_float(pd.to_numeric(grp["crps_ftv"], errors="coerce").mean()) if len(grp) else float("nan"),
            }
        )
    return {"residual_buckets": rows}


def parse_start_visits(vals: list[int]) -> tuple[int, ...]:
    out = tuple(sorted({int(v) for v in vals}))
    bad = [v for v in out if v < 0 or v > 2]
    if bad:
        raise ValueError(f"start visits must be in [0, 1, 2], got {bad}")
    return out


